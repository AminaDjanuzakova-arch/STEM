export function shuffleArray(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function getQuestionsForGame({ difficulty, category, count = 15 }) {
  let pool = QUESTIONS.filter((q) => {
    const diffOk = !difficulty || difficulty === 'all' || q.difficulty === difficulty;
    const catOk = !category || category === 'all' || q.category === category;
    return diffOk && catOk;
  });

  // Если мало вопросов для фильтра — расширяем пул соседними сложностями
  if (pool.length < count) {
    const order = ['easy', 'medium', 'hard', 'expert'];
    const idx = order.indexOf(difficulty);
    pool = QUESTIONS.filter((q) => {
      const catOk = !category || category === 'all' || q.category === category;
      if (!catOk) return false;
      if (!difficulty || difficulty === 'all') return true;
      const qIdx = order.indexOf(q.difficulty);
      return Math.abs(qIdx - idx) <= 1;
    });
  }

  if (pool.length < count) {
    pool = QUESTIONS.filter((q) => !category || category === 'all' || q.category === category);
  }

  if (pool.length < count) {
    pool = [...QUESTIONS];
  }

  return shuffleArray(pool).slice(0, count);
}

